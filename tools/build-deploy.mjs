import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { productionHeaders } from '../deployment/security-headers.mjs';
import './verify-current.cjs';

const root = await fs.realpath(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));
const output = path.resolve(root, 'dist');
const statePath = path.join(root, 'tmp', 'deploy-build-state.json');
const publicEntries = ['index.html', 'assets', 'image', 'image portofolio'];
assert(path.dirname(output) === root && path.basename(output) === 'dist', 'Output must be the project dist folder');
async function collect(directory, prefix = '') {
  const entries = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const relative = prefix ? prefix + '/' + entry.name : entry.name;
    assert(!entry.isSymbolicLink(), 'Deployment excludes symlinks: ' + relative);
    if (entry.isDirectory()) entries.push(...await collect(path.join(directory, entry.name), relative));
    else if (entry.isFile()) entries.push(relative);
  }
  return entries;
}
// Validate the source before replacing previously generated output.
for (const entry of publicEntries) {
  const stat = await fs.lstat(path.join(root, entry));
  assert(!stat.isSymbolicLink(), 'Public entry must not be a symlink: ' + entry);
  if (stat.isDirectory()) await collect(path.join(root, entry));
}
let existingOutput = null;
try { existingOutput = await fs.lstat(output); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
if (existingOutput) {
  assert(existingOutput.isDirectory() && !existingOutput.isSymbolicLink(), 'dist must be a real generated directory');
  const state = JSON.parse(await fs.readFile(statePath, 'utf8'));
  assert(state.output === output && state.root === root, 'Refusing to replace a dist folder not generated by this builder');
  // The resolved target is exactly this project dist directory and has a matching build owner record.
  await fs.rm(output, { recursive: true, force: true });
}
await fs.mkdir(path.dirname(statePath), { recursive: true });
await fs.writeFile(statePath, JSON.stringify({ root, output, status: 'building' }));
await fs.mkdir(output, { recursive: true });
for (const entry of publicEntries) await fs.cp(path.join(root, entry), path.join(output, entry), { recursive: true });
const headers = [{ source: '/(.*)', headers: Object.entries(productionHeaders).map(([key, value]) => ({ key, value })) }];
const config = JSON.parse(await fs.readFile(path.join(root, 'vercel.json'), 'utf8'));
assert.deepEqual(config.headers, headers, 'Vercel headers must match the shared policy');
assert.equal(config.outputDirectory, 'dist');
// Also support deploying the prebuilt folder with the Vercel CLI.
await fs.writeFile(path.join(output, 'vercel.json'), JSON.stringify({ headers }, null, 2) + '\n');
const files = await collect(output);
let bytes = 0;
for (const file of files) bytes += (await fs.stat(path.join(output, file))).size;
await fs.mkdir(path.dirname(statePath), { recursive: true });
await fs.writeFile(statePath, JSON.stringify({ root, output, files: files.length, bytes, generated: new Date().toISOString() }, null, 2));
console.log('BUILD: ' + files.length + ' public files, ' + (bytes / 1024 / 1024).toFixed(2) + ' MiB -> dist');
